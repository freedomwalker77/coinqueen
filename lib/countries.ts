const names = new Intl.DisplayNames(["en"], { type: "region" });

export type ConnectCountryCode = (typeof CONNECT_COUNTRY_CODES)[number];

export function isConnectCountry(code: string): code is ConnectCountryCode {
  return (CONNECT_COUNTRY_CODES as readonly string[]).includes(code.toUpperCase());
}

export function connectCountries() {
  return CONNECT_COUNTRY_CODES.map((code) => ({
    code,
    name: names.of(code) ?? code,
  })).sort((a, b) => a.name.localeCompare(b.name));
}

export function stripeCountryParam(code: string) {
  return code.trim().toLowerCase();
}
